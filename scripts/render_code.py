from manim import *

class MaarifScene(Scene):
    def construct(self):
        # Intro (16s)
        title = Tex("Kesir Çeşitleri ve Dönüşümler", font_size=48)
        self.play(Write(title), run_time=3)
        self.wait(12)
        self.play(FadeOut(title), run_time=1)

        # Basit Kesir (40s)
        pizza1 = VGroup(*[Sector(radius=1.5, angle=TAU/4, start_angle=i*TAU/4, color=BLUE, fill_opacity=0.8 if i<3 else 0.2, stroke_width=2, stroke_color=WHITE) for i in range(4)])
        pizza1.shift(LEFT*3)
        basit_text = Tex("Basit Kesir", font_size=40).shift(RIGHT*2 + UP*1)
        frac_3_4 = MathTex(r"\frac{3}{4}", font_size=60).next_to(basit_text, DOWN)
        self.play(Create(pizza1), run_time=4)
        self.wait(5)
        self.play(Write(basit_text), Write(frac_3_4), run_time=3)
        self.wait(9)
        pay_kucuk = Tex("Pay $<$ Payda", font_size=36).next_to(frac_3_4, DOWN)
        self.play(Write(pay_kucuk), run_time=2)
        self.wait(16)
        self.play(FadeOut(pizza1, basit_text, frac_3_4, pay_kucuk), run_time=1)

        # Bileşik Kesir (50s)
        pizza2_1 = VGroup(*[Sector(radius=1.5, angle=TAU/4, start_angle=i*TAU/4, color=GREEN, fill_opacity=0.8, stroke_width=2, stroke_color=WHITE) for i in range(4)]).shift(LEFT*4)
        pizza2_2 = VGroup(*[Sector(radius=1.5, angle=TAU/4, start_angle=i*TAU/4, color=GREEN, fill_opacity=0.8 if i<3 else 0.2, stroke_width=2, stroke_color=WHITE) for i in range(4)]).shift(LEFT*0.5)
        bilesik_text = Tex("Bileşik Kesir", font_size=40).shift(RIGHT*3.5 + UP*1)
        frac_7_4 = MathTex(r"\frac{7}{4}", font_size=60).next_to(bilesik_text, DOWN)
        self.play(Create(pizza2_1), Create(pizza2_2), run_time=5)
        self.wait(8)
        self.play(Write(bilesik_text), Write(frac_7_4), run_time=3)
        self.wait(14)
        pay_buyuk = Tex("Pay $>$ Payda", font_size=36).next_to(frac_7_4, DOWN)
        self.play(Write(pay_buyuk), run_time=2)
        self.wait(18)

        # Tam Sayılı Kesir (51s)
        tam_text = Tex("Tam Sayılı Kesir", font_size=40).move_to(bilesik_text)
        frac_1_3_4 = MathTex(r"1 \frac{3}{4}", font_size=60).move_to(frac_7_4)
        self.play(FadeOut(bilesik_text, frac_7_4, pay_buyuk), run_time=2)
        self.wait(5)
        self.play(Write(tam_text), Write(frac_1_3_4), run_time=3)
        self.wait(14)
        brace1 = Brace(pizza2_1, DOWN)
        brace1_text = brace1.get_text("1 Tam")
        brace2 = Brace(pizza2_2, DOWN)
        brace2_text = brace2.get_tex(r"\frac{3}{4}")
        self.play(Create(brace1), Write(brace1_text), Create(brace2), Write(brace2_text), run_time=4)
        self.wait(22)
        self.play(FadeOut(pizza2_1, pizza2_2, tam_text, frac_1_3_4, brace1, brace1_text, brace2, brace2_text), run_time=1)

        # Conversion 1: 7/4 -> 1 3/4 (55s)
        conv1_title = Tex(r"Bileşik $\rightarrow$ Tam Sayılı", font_size=40).to_edge(UP)
        self.play(Write(conv1_title), run_time=2)
        self.wait(5)
        div_eq = MathTex("7", "\div", "4").shift(UP*1)
        self.play(Write(div_eq), run_time=2)
        self.wait(10)
        long_div = MathTex(r"7 = 4 \times 1 + 3").next_to(div_eq, DOWN*2)
        self.play(Write(long_div), run_time=3)
        self.wait(10)
        result1 = MathTex(r"\frac{7}{4} = 1 \frac{3}{4}", font_size=50).next_to(long_div, DOWN*2)
        self.play(Write(result1), run_time=3)
        self.wait(19)
        self.play(FadeOut(conv1_title, div_eq, long_div, result1), run_time=1)

        # Conversion 2: 2 3/5 -> 13/5 (68s)
        conv2_title = Tex(r"Tam Sayılı $\rightarrow$ Bileşik", font_size=40).to_edge(UP)
        self.play(Write(conv2_title), run_time=2)
        self.wait(10)
        start_frac = MathTex(r"2 \frac{3}{5}", font_size=60).shift(UP*1)
        self.play(Write(start_frac), run_time=2)
        self.wait(10)
        calc_step = MathTex(r"\frac{2 \times 5 + 3}{5}", font_size=50).next_to(start_frac, DOWN*2)
        self.play(Write(calc_step), run_time=3)
        self.wait(15)
        final_frac = MathTex(r"= \frac{13}{5}", font_size=60).next_to(calc_step, RIGHT)
        self.play(Write(final_frac), run_time=2)
        self.wait(23)
        self.play(FadeOut(conv2_title, start_frac, calc_step, final_frac), run_time=1)

        # Outro (4.7s)
        outro_text = Tex("Maarif Matematik", font_size=50)
        self.play(Write(outro_text), run_time=2)
        self.wait(2.7)
