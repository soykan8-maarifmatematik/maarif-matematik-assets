from manim import *
import numpy as np

config.pixel_height = 1920
config.pixel_width = 1080
config.frame_height = 14.22
config.frame_width = 8.0

class MaarifScene(Scene):
    def construct(self):
        caption1 = Text("Paydasi buyuk olan", font_size=85).shift(UP * 4.5)
        caption1.scale_to_fit_width(7)
        caption2 = Text("her zaman buyuk mudur?", font_size=85).shift(DOWN * 4.5)
        caption2.scale_to_fit_width(7)
        self.play(Write(caption1), Write(caption2))
        self.wait(2)
        self.play(FadeOut(caption1), FadeOut(caption2))
        circle = Circle(radius=3, color=WHITE)
        self.play(Create(circle))
        sector2 = Sector(radius=3, angle=PI, color=RED, fill_opacity=0.8)
        sector2.move_to(circle.get_center())
        frac_half = MathTex(r"\frac{1}{2}", font_size=110).shift(UP * 4.5)
        caption3 = Text("Bir pizzayi 2ye bol", font_size=85).shift(DOWN * 4.5)
        caption3.scale_to_fit_width(7)
        self.play(Create(sector2), Write(frac_half), Write(caption3))
        self.wait(2)
        sector4 = Sector(radius=3, angle=PI/2, color=BLUE, fill_opacity=0.8)
        sector4.move_to(circle.get_center())
        frac_quarter = MathTex(r"\frac{1}{4}", font_size=110).shift(UP * 4.5)
        caption4 = Text("4e bolersen dilim kuculur", font_size=85).shift(DOWN * 4.5)
        caption4.scale_to_fit_width(7)
        self.play(ReplacementTransform(sector2, sector4), ReplacementTransform(frac_half, frac_quarter), ReplacementTransform(caption3, caption4))
        self.wait(2)
        sector8 = Sector(radius=3, angle=PI/4, color=GREEN, fill_opacity=0.8)
        sector8.move_to(circle.get_center())
        frac_eighth = MathTex(r"\frac{1}{8}", font_size=110).shift(UP * 4.5)
        caption5 = Text("8e bolersen daha da kuculur", font_size=85).shift(DOWN * 4.5)
        caption5.scale_to_fit_width(7)
        self.play(ReplacementTransform(sector4, sector8), ReplacementTransform(frac_quarter, frac_eighth), ReplacementTransform(caption4, caption5))
        self.wait(2)
        caption6 = Text("Yani payda buyudukce", font_size=85).shift(DOWN * 3.5)
        caption6.scale_to_fit_width(7)
        caption7 = Text("kesir kuculur", font_size=85).shift(DOWN * 4.5)
        caption7.scale_to_fit_width(7)
        self.play(ReplacementTransform(caption5, caption6), Write(caption7))
        self.play(Indicate(frac_eighth))
        self.wait(2)
        self.play(FadeOut(circle), FadeOut(sector8), FadeOut(frac_eighth), FadeOut(caption6), FadeOut(caption7))
        cta1 = Text("Maarif Matematik ile", font_size=85).shift(UP * 1)
        cta1.scale_to_fit_width(7)
        cta2 = Text("mantigini kavra", font_size=85).shift(DOWN * 0.5)
        cta2.scale_to_fit_width(7)
        cta3 = Text("takipte kal", font_size=85).shift(DOWN * 2)
        cta3.scale_to_fit_width(7)
        self.play(Write(cta1), Write(cta2), Write(cta3))
        self.wait(2)